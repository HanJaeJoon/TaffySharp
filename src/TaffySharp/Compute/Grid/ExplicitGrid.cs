namespace TaffySharp;

/// <summary>The auto-repeat fit strategy to use.</summary>
internal enum AutoRepeatStrategy
{
    /// <summary>If the grid container has a definite size or max size in the relevant axis: the number of repetitions is the largest possible positive integer that does not cause the grid to overflow the content box of its grid container.</summary>
    MaxRepetitionsThatDoNotOverflow,

    /// <summary>If the grid container has a definite min size in the relevant axis: the number of repetitions is the smallest possible positive integer that fulfills that minimum requirement.</summary>
    MinRepetitionsThatDoOverflow,
}

/// <summary>Helper functions for initializing GridTrack's from styles. This mainly consists of evaluating GridAutoTracks.</summary>
internal static class ExplicitGrid
{
    /// <summary>
    /// Compute the number of rows and columns in the explicit grid.
    /// Returns (auto repetition count, explicit track count).
    /// </summary>
    public static (ushort AutoRepetitionCount, ushort TrackCount) ComputeExplicitGridSizeInAxis(
        IGridContainerStyle style,
        float? autoFitContainerSize,
        AutoRepeatStrategy autoFitStrategy,
        Func<object, float, float> resolveCalcValue,
        AbsoluteAxis axis)
    {
        IReadOnlyList<GridTemplateComponent>? template = style.GridTemplateTracks(axis);
        if (template is null)
        {
            return (0, 0);
        }

        // If template contains no tracks, then there are trivially zero explicit tracks
        if (template.Count == 0)
        {
            return (0, 0);
        }

        // If there are any repetitions that contains no tracks, then the whole definition should be considered invalid
        // and we default to no explicit tracks
        foreach (GridTemplateComponent trackDef in template)
        {
            if (trackDef.Repetition is GridTemplateRepetition repeat && repeat.TrackCount == 0)
            {
                return (0, 0);
            }
        }

        // Compute that number of track generated by single track definition and repetitions with a fixed repetition count
        // (clamping to the maximum track limit to prevent arithmetic overflow)
        long nonAutoRepeatingSum = 0;
        foreach (GridTemplateComponent trackDef in template)
        {
            if (trackDef.Repetition is not GridTemplateRepetition repeat)
            {
                nonAutoRepeatingSum += 1;
            }
            else if (repeat.Count.Kind == RepetitionCountKind.Count)
            {
                nonAutoRepeatingSum += (long)repeat.Count.Value * repeat.TrackCount;
            }
        }

        ushort nonAutoRepeatingTrackCount = (ushort)Math.Min(nonAutoRepeatingSum, GridConstants.MaxGridTracks);

        ushort autoRepetitionCount = (ushort)template.Count(trackDef => trackDef.IsAutoRepetition());
        bool allTrackDefsHaveFixedComponent = template.All(trackDef => trackDef.Repetition is GridTemplateRepetition repeat
            ? repeat.Tracks.All(sizingFunction => sizingFunction.HasFixedComponent())
            : trackDef.SingleTrack.HasFixedComponent());

        bool templateIsValid = autoRepetitionCount == 0 || (autoRepetitionCount == 1 && allTrackDefsHaveFixedComponent);

        // If the template is invalid because it contains multiple auto-repetition definitions or it combines an auto-repetition
        // definition with non-fixed-size track sizing functions, then disregard it entirely and default to zero explicit tracks
        if (!templateIsValid)
        {
            return (0, 0);
        }

        // If there are no repetitions, then the number of explicit tracks is simply equal to the lengths of the track definition
        // vector (as each item in the Vec represents one track).
        if (autoRepetitionCount == 0)
        {
            return (0, nonAutoRepeatingTrackCount);
        }

        uint autoRepeatInsertionPoint = 0;
        GridTemplateRepetition? repetitionDefinition = null;
        foreach (GridTemplateComponent def in template)
        {
            if (def.Repetition is not GridTemplateRepetition repeat)
            {
                autoRepeatInsertionPoint = SaturatingAdd(autoRepeatInsertionPoint, 1);
            }
            else if (repeat.Count.Kind == RepetitionCountKind.Count)
            {
                autoRepeatInsertionPoint = SaturatingAdd(autoRepeatInsertionPoint, (uint)repeat.Count.Value * repeat.TrackCount);
            }
            else
            {
                repetitionDefinition = repeat;
                break;
            }
        }

        List<TrackSizingFunction> repetitionTracks = repetitionDefinition!.Tracks;
        ushort repetitionTrackCount = repetitionDefinition.TrackCount;

        // Determine the number of repetitions
        uint numRepetitions;
        if (autoFitContainerSize is not float innerContainerSize)
        {
            numRepetitions = 1;
        }
        else
        {
            float? parentSize = innerContainerSize;

            float nonRepeatingTrackUsedSpace = 0f;
            foreach (GridTemplateComponent trackDef in template)
            {
                if (trackDef.Repetition is not GridTemplateRepetition repeat)
                {
                    nonRepeatingTrackUsedSpace += TrackDefiniteValue(trackDef.SingleTrack, parentSize, resolveCalcValue);
                }
                else if (repeat.Count.Kind == RepetitionCountKind.Count)
                {
                    float sum = 0f;
                    foreach (TrackSizingFunction sizingFunction in repeat.Tracks)
                    {
                        sum += TrackDefiniteValue(sizingFunction, parentSize, resolveCalcValue);
                    }

                    nonRepeatingTrackUsedSpace += sum * repeat.Count.Value;
                }
            }

            float gapSize = style.Gap.GetAbs(axis).ResolveOrZero(innerContainerSize, resolveCalcValue);

            // Compute the amount of space that a single repetition of the repeated track list takes
            float perRepetitionTrackUsedSpace = 0f;
            foreach (TrackSizingFunction sizingFunction in repetitionTracks)
            {
                perRepetitionTrackUsedSpace += TrackDefiniteValue(sizingFunction, parentSize, resolveCalcValue);
            }

            // We special case the first repetition here because the number of gaps in the first repetition
            // depends on the number of non-repeating tracks in the template
            float firstRepetitionAndNonRepeatingTracksUsedSpace = nonRepeatingTrackUsedSpace
                + perRepetitionTrackUsedSpace
                + (Math.Max((long)nonAutoRepeatingTrackCount + repetitionTrackCount - 1, 0) * gapSize);

            // If a single repetition already overflows the container then we return 1 as the repetition count
            // (the number of repetitions is floored at 1)
            if (firstRepetitionAndNonRepeatingTracksUsedSpace > innerContainerSize)
            {
                numRepetitions = 1;
            }
            else
            {
                float perRepetitionGapUsedSpace = repetitionTrackCount * gapSize;
                float perRepetitionUsedSpace = perRepetitionTrackUsedSpace + perRepetitionGapUsedSpace;
                float numRepetitionThatFit = (innerContainerSize - firstRepetitionAndNonRepeatingTracksUsedSpace) / perRepetitionUsedSpace;

                // If the container size is a preferred or maximum size:
                //   Then we return the maximum number of repetitions that fit into the container without overflowing.
                // If the container size is a minimum size:
                //   - Then we return the minimum number of repetitions required to overflow the size.
                //
                // In all cases we add the additional repetition that was already accounted for in the special-case computation above
                // Note: as-casts from f32 to u32 saturate, so a huge or infinite number of repetitions
                // (e.g. due to zero-sized tracks) resolves to u32::MAX and is clamped below
                numRepetitions = autoFitStrategy switch
                {
                    AutoRepeatStrategy.MaxRepetitionsThatDoNotOverflow => SaturatingAdd(SaturatingToU32(MathHelpers.Floor(numRepetitionThatFit)), 1),
                    _ => SaturatingAdd(SaturatingToU32(MathHelpers.Ceil(numRepetitionThatFit)), 1),
                };
            }
        }

        // Clamp the number of repetitions based on the auto-repeat's insertion point so that tracks
        // before it are preserved and tracks after it are truncated in source order.
        // https://www.w3.org/TR/css-grid-1/#overlarge-grids
        uint remainingTracks = GridConstants.MaxGridTracks > autoRepeatInsertionPoint ? GridConstants.MaxGridTracks - autoRepeatInsertionPoint : 0;
        ushort clampedRepetitions;
        if (remainingTracks == 0)
        {
            clampedRepetitions = 0;
        }
        else
        {
            uint maxRepetitions = (remainingTracks + repetitionTrackCount - 1) / repetitionTrackCount;
            clampedRepetitions = (ushort)Math.Min(Math.Max(numRepetitions, 1u), maxRepetitions);
        }

        ushort gridTemplateTrackCount = (ushort)Math.Min(
            nonAutoRepeatingTrackCount + ((uint)repetitionTrackCount * clampedRepetitions),
            GridConstants.MaxGridTracks);

        return (clampedRepetitions, gridTemplateTrackCount);
    }

    /// <summary>
    /// Resolve the track sizing function to a definite value (the max of its min and max sizing functions when both are definite).
    /// Only called for track definitions that have a fixed component.
    /// </summary>
    private static float TrackDefiniteValue(TrackSizingFunction sizingFunction, float? parentSize, Func<object, float, float> calcResolver)
    {
        float? maxSize = sizingFunction.Max.DefiniteValue(parentSize, calcResolver);
        float? minSize = sizingFunction.Min.DefiniteValue(parentSize, calcResolver);
        float? value = maxSize is float max ? max.MaybeMax(minSize) : minSize;
        return value ?? throw new InvalidOperationException("track sizing function has no definite value");
    }

    private static uint SaturatingAdd(uint a, uint b) => a > uint.MaxValue - b ? uint.MaxValue : a + b;

    /// <summary>Rust `f32 as u32`: saturating, with NaN mapping to 0.</summary>
    private static uint SaturatingToU32(float value)
    {
        if (float.IsNaN(value) || value <= 0f)
        {
            return 0;
        }

        return value >= 4294967295f ? uint.MaxValue : (uint)value;
    }

    /// <summary>
    /// Resolve the track sizing functions of explicit tracks, automatically created tracks, and gutters
    /// given a set of track counts and all of the relevant styles.
    /// </summary>
    public static void InitializeGridTracks(
        List<GridTrack> tracks,
        TrackCounts counts,
        IGridContainerStyle style,
        AbsoluteAxis axis,
        ushort autoRepetitionCount,
        Func<int, bool> trackHasItems)
    {
        // Extract styles
        IReadOnlyList<GridTemplateComponent>? trackTemplate;
        IReadOnlyList<TrackSizingFunction> autoTracks;
        LengthPercentage gap;
        if (axis == AbsoluteAxis.Horizontal)
        {
            trackTemplate = style.GridTemplateColumns;
            autoTracks = style.GridAutoColumns;
            gap = style.Gap.Width;
        }
        else
        {
            trackTemplate = style.GridTemplateRows;
            autoTracks = style.GridAutoRows;
            gap = style.Gap.Height;
        }

        // Clear vector (in case this is a re-layout), reserve space for all tracks ahead of time to reduce allocations,
        // and push the initial gutter
        tracks.Clear();
        tracks.Capacity = Math.Max(tracks.Capacity, (counts.Len() * 2) + 1);
        tracks.Add(GridTrack.Gutter(gap));

        int autoTrackCount = autoTracks.Count;

        // Create negative implicit tracks
        if (counts.NegativeImplicit > 0)
        {
            if (autoTrackCount == 0)
            {
                CreateImplicitTracks(tracks, counts.NegativeImplicit, RepeatForever(TrackSizingFunction.Auto), gap);
            }
            else
            {
                int offset = autoTrackCount - (counts.NegativeImplicit % autoTrackCount);
                CreateImplicitTracks(tracks, counts.NegativeImplicit, Cycle(autoTracks).Skip(offset), gap);
            }
        }

        int currentTrackIndex = counts.NegativeImplicit;

        // The maximum index up to which explicit tracks may be created. The explicit track count is clamped
        // to MAX_GRID_TRACKS, so track creation from the template must be truncated to match.
        int explicitTrackLimit = counts.NegativeImplicit + counts.Explicit;

        // Create explicit tracks
        // An explicit check against the count (rather than just relying on track_template being empty) is required here
        // because a count of zero can result from the track_template being invalid, in which case it should be ignored.
        if (counts.Explicit > 0 && trackTemplate is not null)
        {
            foreach (GridTemplateComponent trackSizingFunction in trackTemplate)
            {
                if (trackSizingFunction.Repetition is not GridTemplateRepetition repeat)
                {
                    if (currentTrackIndex < explicitTrackLimit)
                    {
                        TrackSizingFunction sizingFunction = trackSizingFunction.SingleTrack;
                        tracks.Add(GridTrack.New(sizingFunction.MinSizingFunction(), sizingFunction.MaxSizingFunction()));
                        tracks.Add(GridTrack.Gutter(gap));
                        currentTrackIndex += 1;
                    }
                }
                else if (repeat.Count.Kind == RepetitionCountKind.Count)
                {
                    int repeatedTrackCount = (int)Math.Min((long)repeat.TrackCount * repeat.Count.Value, explicitTrackLimit - currentTrackIndex);
                    foreach (TrackSizingFunction sizingFunction in Cycle(repeat.Tracks).Take(repeatedTrackCount))
                    {
                        tracks.Add(GridTrack.New(sizingFunction.MinSizingFunction(), sizingFunction.MaxSizingFunction()));
                        tracks.Add(GridTrack.Gutter(gap));
                        currentTrackIndex += 1;
                    }
                }
                else
                {
                    int autoRepeatedTrackCount = (int)Math.Min((long)repeat.TrackCount * autoRepetitionCount, explicitTrackLimit - currentTrackIndex);
                    foreach (TrackSizingFunction trackDef in Cycle(repeat.Tracks).Take(autoRepeatedTrackCount))
                    {
                        GridTrack track = GridTrack.New(trackDef.MinSizingFunction(), trackDef.MaxSizingFunction());
                        GridTrack gutter = GridTrack.Gutter(gap);

                        // Auto-fit tracks that don't contain should be collapsed.
                        if (repeat.Count.Kind == RepetitionCountKind.AutoFit && !trackHasItems(currentTrackIndex))
                        {
                            track.Collapse();
                            gutter.Collapse();
                        }

                        tracks.Add(track);
                        tracks.Add(gutter);
                        currentTrackIndex += 1;
                    }

                    // Is this auto-repeat at the very end of the track list?
                    bool isLast = currentTrackIndex == counts.Len();

                    // When collapsing auto-fit tracks (in the loop just above), we collapse the gutter after collapsed
                    // tracks but not the gutter before. This is correct so long as there is another non-collapsed track
                    // somewhere in the track list after the collapsed track.
                    //
                    // However, if the auto-fit repeat is at the very end of the track list, then there will be no such track.
                    // In this case we need to iterate backwards through the track list until we find a non-collapsed track and
                    // collapse the gutter just after that track.
                    //
                    // As all of the other tracks and gutters we find along the way will already be collapsed, we simplify the
                    // implementation to collapsing all tracks and gutters until we find the first non-collapsed track.
                    if (repeat.Count.Kind == RepetitionCountKind.AutoFit && isLast)
                    {
                        for (int i = tracks.Count - 1; i >= 0; i--)
                        {
                            GridTrack previousTrack = tracks[i];
                            if (previousTrack.Kind == GridTrackKind.Track && !previousTrack.IsCollapsed)
                            {
                                break;
                            }

                            previousTrack.Collapse();
                        }
                    }
                }
            }
        }

        ushort gridAreaTracks = (ushort)(counts.NegativeImplicit + counts.Explicit - currentTrackIndex);

        // Create positive implicit tracks
        ushort positiveCount = (ushort)(counts.PositiveImplicit + gridAreaTracks);
        if (autoTrackCount == 0)
        {
            CreateImplicitTracks(tracks, positiveCount, RepeatForever(TrackSizingFunction.Auto), gap);
        }
        else
        {
            CreateImplicitTracks(tracks, positiveCount, Cycle(autoTracks), gap);
        }

        // Mark first and last grid lines as collapsed
        tracks[0].Collapse();
        tracks[tracks.Count - 1].Collapse();
    }

    /// <summary>Utility function for repeating logic of creating implicit tracks.</summary>
    private static void CreateImplicitTracks(List<GridTrack> tracks, ushort count, IEnumerable<TrackSizingFunction> autoTracksIter, LengthPercentage gap)
    {
        foreach (TrackSizingFunction trackDef in autoTracksIter.Take(count))
        {
            tracks.Add(GridTrack.New(trackDef.MinSizingFunction(), trackDef.MaxSizingFunction()));
            tracks.Add(GridTrack.Gutter(gap));
        }
    }

    /// <summary>Rust <c>Iterator::cycle</c>: endlessly repeat the items (yields nothing if there are none).</summary>
    private static IEnumerable<T> Cycle<T>(IReadOnlyList<T> items)
    {
        if (items.Count == 0)
        {
            yield break;
        }

        while (true)
        {
            foreach (T item in items)
            {
                yield return item;
            }
        }
    }

    private static IEnumerable<T> RepeatForever<T>(T item)
    {
        while (true)
        {
            yield return item;
        }
    }
}
